CREATE TABLE PENALT {
    ID INT PRIMARY KEY AUTO_INCREMENT,
    FK_JOGADOR_COBRANDO INT NOT NULL,
    FK_PARTIDA INT NOT NULL,
    MINUTO TIME NOT NULL,
    RESULTADO ENUM('GOL', 'DEFENDIDO') NOT NULL,
    FK_GOL INT ,
    FOREIGN KEY(FK_JOGADOR_COBRANDO) REFERENCES JOGADOR(ID),
    FOREIGN KEY(FK_PARTIDA) REFERENCES PARTIDA(ID),
    FOREIGN KEY (FK_GOL) REFERENCES GOL_PARTIDA(ID)
};

CREATE TABLE FUNCAO{
    ID INT NOT NULL PRIMARY KEY AUTO_INCREMENT,
    NOME VARCHAR(255) NOT NULL
};

CREATE TABLE JOGADOR{
    ID INT PRIMARY KEY AUTO_INCREMENT,
    NOME VARCHAR(255) NOT NULL,
    NOME_CAMISA INT NOT NULL,
    NUMERO_CAMISA INT NOT NULL,
    FK_SELECAO INT NOT NULL,
    FK_PAIS INT NOT NULL,
    FK_FUNCAO INT NOT NULL,
    FOREIGN KEY(FK_SELECAO) REFERENCES SELECAO(ID),
    FOREIGN KEY(FK_PAIS) REFERENCES PAIS(ID),
    FOREIGN KEY(FK_FUNCAO) REFERENCES FUNCAO(ID)
};

CREATE TABLE ARBITRO{
    ID INT NOT NULL PRIMARY KEY AUTO_INCREMENT,
    NOME VARCHAR(255) NOT NULL,
    FK_PAIS INT NOT NULL,
    FOREIGN KEY(FK_PAIS) REFERENCES PAIS(ID)

};

CREATE TABLE ARBITRO_PARTIDA{
    ID INT NOT NULL AUTO_INCREMENT PRIMARY KEY
    FK_ARBITRO INT NOT NULL,
    FK_PARTIDA INT NOT NULL,
    FK_FUNÇÃO INT NOT NULL,
    FOREIGN KEY(FK_ARBITRO) REFERENCES ARBITRO(ID),
    FOREIGN KEY(FK_PARTIDA) REFERENCES PARTIDA(ID),
    FOREIGN KEY(FK_FUNÇÃO) REFERENCES FUNCAO(ID)
};

CREATE TABLE RESULTADO_PARTIDA{
    ID INT NOT NULL PRIMARY KEY AUTO_INCREMENT,
    RESULTADO ENUM('E', 'VS1', 'VS2'),
    FK_SELECAO1 INT NOT NULL,
    FK_SELECAO2 INT NOT NULL,
    FOREIGN KEY(FK_SELECAO1) REFERENCES SELECAO(ID),
    FOREIGN KEY(FK_SELECAO2) REFERENCES SELECAO(ID)
};
